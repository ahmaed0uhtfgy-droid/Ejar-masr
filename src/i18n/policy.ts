export interface PolicyVars { fee: number; feePayer: 'owner' | 'tenant' | 'split'; claimDays: number; payoutDays: number; refundDays: number; disputeDays: number; cancelAfterPayment: 'blocked' | 'request'; cancelFeePercent: number }

export function policyVars(v: PolicyVars): Record<string, string> {
  return {
    '{fee}': v.fee > 0 ? `${v.fee}٪` : 'صفر',
    '{feePayer}': v.feePayer === 'tenant' ? 'العمولة بتتضاف على المبلغ اللي المستأجر بيدفعه، والمالك بيستلم الإيجار كامل.'
      : v.feePayer === 'split' ? 'العمولة بتتقسم بالتساوي بين المالك (بتتخصم من حصته) والمستأجر (بتتضاف على دفعته).'
      : 'العمولة بتتخصم من حصة المالك، والمستأجر مبيدفعش رسوم إضافية.',
    '{claimDays}': String(v.claimDays), '{payoutDays}': String(v.payoutDays), '{refundDays}': String(v.refundDays), '{disputeDays}': String(v.disputeDays),
    '{cancelPolicy}': v.cancelAfterPayment === 'request'
      ? `بعد الدفع وقبل تأكيد الاستلام: تقدر تطلب إلغاء العقد من صفحة "إيجاراتي"، والإدارة بتراجع الطلب. لو اتوافق عليه، بيتم رد المبلغ بعد خصم رسوم إلغاء ${v.cancelFeePercent}٪.`
      : 'بعد الدفع وقبل تأكيد الاستلام: الإلغاء مش متاح من الموقع. تواصل مع الإدارة لو عندك ظرف استثنائي.',
  }
}

export const fillTokens = (t: string, vars: Record<string, string>): string => Object.entries(vars).reduce((s, [k, v]) => s.split(k).join(v), t)

